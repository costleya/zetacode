import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";

const bundle = await readFile(process.argv[2] ?? "out/extension.mjs", "utf8");
const packageRoots = new Set();
for (const line of bundle.split("\n")) {
  if (!line.startsWith("//#region ")) continue;
  const match = line.match(/node_modules\/(\.pnpm\/[^/]+\/node_modules\/(?:@[^/]+\/)?[^/]+)/);
  if (match) packageRoots.add(path.resolve("node_modules", match[1]));
}
if (!packageRoots.size) throw new Error("No bundled dependency locations found");
const sections = [];
for (const root of packageRoots) {
  const metadata = JSON.parse(await readFile(path.join(root, "package.json"), "utf8"));
  const names = (await readdir(root)).filter((name) =>
    /^(licen[sc]e|copying|notice)(\.|$)/i.test(name),
  );
  const texts = await Promise.all(
    names.sort().map((name) => readFile(path.join(root, name), "utf8")),
  );
  if (!texts.length && metadata.name === "@bufbuild/protobuf") {
    texts.push(await readFile("licenses/bufbuild-protobuf-LICENSE", "utf8"));
    texts.push(await readFile("licenses/bufbuild-protobuf-BSD", "utf8"));
  }
  if (!texts.length) throw new Error(`Missing license text for ${metadata.name}`);
  sections.push({
    name: metadata.name,
    text: `## ${metadata.name} ${metadata.version}\n\nLicense: ${metadata.license ?? "see below"}\n\n\`\`\`text\n${texts.join("\n\n").replaceAll("\r\n", "\n").trim()}\n\`\`\`\n`,
  });
}
sections.sort((a, b) => a.name.localeCompare(b.name));
await writeFile(
  "THIRD_PARTY_NOTICES.md",
  "# Bundled dependency notices\n\nLicense texts supplied by the packages included in the extension bundle. Generated by `node tools/bundled-notices.mjs`.\n\n" +
    sections.map((section) => section.text).join("\n"),
);
console.log(`Recorded notices for ${sections.length} bundled packages.`);
